function seedSampleDfmea(projectId: number) {
  syncDfmeaFromRequirements(projectId)
  const db = getDb()
  const reqs = db.requirements.filter((r) => r.projectId === projectId)
  const byNo = new Map(reqs.map((r) => [r.reqNo, r]))
  for (const row of SAMPLE_DFMEA) {
    const product = byNo.get(row.product)
    const module = row.module ? byNo.get(row.module) : undefined
    const part = row.part ? byNo.get(row.part) : undefined
    if (!product) continue
    if (row.fe) updateDfmeaAnalysis(projectId, 'failureEffect', product.id, row.fe)
    if (module && row.fm) updateDfmeaAnalysis(projectId, 'failureMode', module.id, row.fm)
    if (part && row.fc) updateDfmeaAnalysis(projectId, 'failureCause', part.id, row.fc)
  }
  const latest = getDb()
  for (const row of SAMPLE_DFMEA) {
    const product = byNo.get(row.product)
    const module = row.module ? byNo.get(row.module) : undefined
    const part = row.part ? byNo.get(row.part) : undefined
    if (!product) continue
    const rec = latest.dfmeaRecords.find(
      (r) =>
        r.projectId === projectId &&
        r.productReqId === product.id &&
        r.moduleReqId === module?.id &&
        r.partReqId === part?.id &&
        (row.fe ? r.failureEffect === row.fe : true) &&
        (row.fm ? r.failureMode === row.fm : true) &&
        (row.fc ? r.failureCause === row.fc : true),
    )
    if (!rec) continue
    updateDfmeaRecord(rec.id, {
      bomItemId: part?.bomItemId ?? rec.bomItemId,
      severity: row.s ?? rec.severity,
      occurrence: row.o ?? rec.occurrence,
      detection: row.d ?? rec.detection,
      preventionControl: row.prevention ?? rec.preventionControl,
      detectionControl: row.detection ?? rec.detectionControl,
      actionStatus: rec.actionStatus && rec.actionStatus !== '未开始' ? rec.actionStatus : '进行中',
    })
  }
}

