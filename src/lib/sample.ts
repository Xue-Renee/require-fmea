function seedSampleBom(projectId: number) {
  const existingBom = getDb().bomItems.filter((b) => b.projectId === projectId)
  const bomByNo = new Map(existingBom.map((b) => [b.partNo, b.id]))
  for (const item of SAMPLE_BOM_ITEMS) {
    if (bomByNo.has(item.partNo)) continue
    const created = createBomItem(projectId, item)
    bomByNo.set(created.partNo, created.id)
  }
  const db = getDb()
  for (const [reqNo, partNo] of SAMPLE_PART_BOM_LINKS) {
    const req = db.requirements.find((r) => r.projectId === projectId && r.reqNo === reqNo)
    const bomId = bomByNo.get(partNo)
    if (req && bomId && req.bomItemId !== bomId) updateRequirement(req.id, { bomItemId: bomId, acceptanceMethod: req.acceptanceMethod })
  }
  return bomByNo
}

